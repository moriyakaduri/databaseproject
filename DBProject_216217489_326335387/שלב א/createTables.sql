-- 2createTables.sql
-- HOSPITAL LABORATORY - PostgreSQL 16 / pgAdmin
-- Based on the lecturer-approved ERD / DSD: 8 tables, no added columns.
-- Run in your NEW, EMPTY project database (hospital_lab_db).
-- Order: independent tables first, then dependent tables.
-- PostgreSQL stores unquoted table/column names in lower case.

BEGIN;

-- 1. PATIENT: patient details (shared entity)
CREATE TABLE PATIENT (
    PatientID       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDNumber        VARCHAR(9)   NOT NULL UNIQUE,
    FirstName       VARCHAR(50)  NOT NULL,
    LastName        VARCHAR(50)  NOT NULL,
    DateOfBirth     DATE         NOT NULL,
    Gender          VARCHAR(10),
    Phone           VARCHAR(15),
    CONSTRAINT chk_patient_gender CHECK (Gender IN ('M', 'F', 'other'))
);

-- 2. DOCTOR: doctors requesting laboratory tests (shared entity)
CREATE TABLE DOCTOR (
    DoctorID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LicenseNumber   VARCHAR(20)  NOT NULL UNIQUE,
    FirstName       VARCHAR(50)  NOT NULL,
    LastName        VARCHAR(50)  NOT NULL,
    Specialty       VARCHAR(60)  NOT NULL,
    Phone           VARCHAR(15)
);

-- 3. TESTTYPE: laboratory test catalog
CREATE TABLE TESTTYPE (
    TestTypeID      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TestCode        VARCHAR(30)  NOT NULL UNIQUE,
    TestName        VARCHAR(100) NOT NULL,
    Category        VARCHAR(60),
    DefaultUnit     VARCHAR(30)
);

-- 4. LABTECHNICIAN: laboratory staff
CREATE TABLE LABTECHNICIAN (
    TechnicianID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName           VARCHAR(50)  NOT NULL,
    LastName            VARCHAR(50)  NOT NULL,
    CertificationNumber VARCHAR(30)  NOT NULL UNIQUE,
    Phone               VARCHAR(15)
);

-- 5. TESTORDER: an order belongs to exactly one patient and one doctor
CREATE TABLE TESTORDER (
    OrderID         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderedAt       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Priority        VARCHAR(20) NOT NULL DEFAULT 'Routine',
    Notes           TEXT,
    PatientID       INTEGER NOT NULL,
    DoctorID        INTEGER NOT NULL,
    CONSTRAINT chk_testorder_priority CHECK (Priority IN ('Routine', 'Urgent', 'STAT')),
    CONSTRAINT fk_testorder_patient FOREIGN KEY (PatientID)
        REFERENCES PATIENT (PatientID),
    CONSTRAINT fk_testorder_doctor FOREIGN KEY (DoctorID)
        REFERENCES DOCTOR (DoctorID)
);

-- 6. LABTEST: an ordered test of a given type
-- TechnicianID is deliberately nullable, as shown by (FK)(O) in the DSD.
CREATE TABLE LABTEST (
    LabTestID          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Status             VARCHAR(30) NOT NULL DEFAULT 'Scheduled',
    PerformedLocation  VARCHAR(100),
    ScheduledAt        TIMESTAMP,
    StartedAt          TIMESTAMP,
    CompletedAt        TIMESTAMP,
    OrderID            INTEGER NOT NULL,
    TestTypeID         INTEGER NOT NULL,
    TechnicianID       INTEGER,
    CONSTRAINT chk_labtest_status CHECK (Status IN ('Scheduled', 'InProgress', 'Completed', 'Cancelled')),
    CONSTRAINT fk_labtest_order FOREIGN KEY (OrderID)
        REFERENCES TESTORDER (OrderID),
    CONSTRAINT fk_labtest_type FOREIGN KEY (TestTypeID)
        REFERENCES TESTTYPE (TestTypeID),
    CONSTRAINT fk_labtest_technician FOREIGN KEY (TechnicianID)
        REFERENCES LABTECHNICIAN (TechnicianID)
);

-- 7. TESTRESULT: at most one result per laboratory test
CREATE TABLE TESTRESULT (
    ResultID        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NumericValue    NUMERIC(12,3),
    TextValue       TEXT,
    Unit            VARCHAR(30),
    ResultedAt      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IsAbnormal      BOOLEAN NOT NULL DEFAULT FALSE,
    LabTestID       INTEGER NOT NULL UNIQUE,
    CONSTRAINT chk_testresult_has_value CHECK (NumericValue IS NOT NULL OR TextValue IS NOT NULL),
    CONSTRAINT fk_testresult_labtest FOREIGN KEY (LabTestID)
        REFERENCES LABTEST (LabTestID)
);

-- 8. LABALERT: a result may trigger multiple alerts
CREATE TABLE LABALERT (
    AlertID         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Severity        VARCHAR(20) NOT NULL,
    Message         TEXT NOT NULL,
    CreatedAt       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    Status          VARCHAR(30) NOT NULL DEFAULT 'Open',
    AcknowledgedAt  TIMESTAMP,
    ResultID        INTEGER NOT NULL,
    CONSTRAINT chk_labalert_severity CHECK (Severity IN ('Low', 'Medium', 'High', 'Critical')),
    CONSTRAINT chk_labalert_status CHECK (Status IN ('Open', 'Acknowledged', 'Resolved')),
    CONSTRAINT fk_labalert_result FOREIGN KEY (ResultID)
        REFERENCES TESTRESULT (ResultID)
);

COMMIT;
