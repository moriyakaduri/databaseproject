"""Deterministic synthetic data, Python stdlib only. Run after audited baseline.
Input orders.csv is exported from the original DB, ordered by orderid.
Output never deletes/updates existing records. Duplicate IDs cause rollback.
"""
import csv
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent
orders = list(csv.DictReader((ROOT / 'orders.csv').open(encoding='utf-8-sig')))
assert len(orders) == 5000, 'Expected audited original orders'

def sql(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"

def insert(out, table, columns, rows):
    # Batches reduce query overhead while retaining portable plain INSERT SQL.
    for offset in range(0, len(rows), 500):
        out.write(f'INSERT INTO {table} ({columns}) VALUES\n')
        out.write(',\n'.join('(' + ','.join(map(sql, r)) + ')' for r in rows[offset:offset+500]))
        out.write(';\n')

tests, results, alerts = [], [], []
for i in range(20000):
    order = orders[i % len(orders)]
    labid = 10001 + i
    typeid = 21 + i % 480
    scheduled = datetime.fromisoformat(order['orderedat']) + timedelta(days=2, minutes=i % 60)
    completed = i % 5 != 0
    status = 'Completed' if completed else ('Scheduled' if i % 10 == 0 else 'InProgress')
    started = scheduled + timedelta(minutes=15) if status != 'Scheduled' else None
    ended = scheduled + timedelta(minutes=75) if completed else None
    tech = 81 + i % 420 if status != 'Scheduled' else None
    tests.append((labid,status,'Demo laboratory '+str(i%4+1),scheduled,started,ended,int(order['orderid']),typeid,tech))
    if completed:
        resultid = 8001 + len(results)
        abnormal = len(results) % 10 == 0
        resulttime = ended + timedelta(minutes=10)
        # New catalog variants marked microbiology carry text results.
        text_type = typeid % 4 == 2
        results.append((resultid, None if text_type else round(10+(i%800)/10,3),
                        ('Synthetic positive' if abnormal else 'Synthetic negative') if text_type else None,
                        None if text_type else 'demo-unit',resulttime,abnormal,labid))
        if abnormal:
            alertid = 1558 + len(alerts)
            created = resulttime + timedelta(minutes=5)
            acknowledged = created + timedelta(minutes=30) if len(alerts)%3 else None
            alerts.append((alertid,'High' if i%3 else 'Medium','Synthetic demonstration alert; not clinical guidance',
                           created,'Acknowledged' if acknowledged else 'Open',acknowledged,resultid))

assert (len(tests),len(results),len(alerts)) == (20000,16000,1600)
with (ROOT / 'generated.sql').open('w',encoding='utf-8',newline='\n') as out:
    out.write('-- Generated by generate_data.py. SYNTHETIC DATA ONLY. Run once.\nBEGIN;\n')
    insert(out,'labtest','labtestid,status,performedlocation,scheduledat,startedat,completedat,orderid,testtypeid,technicianid',tests)
    insert(out,'testresult','resultid,numericvalue,textvalue,unit,resultedat,isabnormal,labtestid',results)
    insert(out,'labalert','alertid,severity,message,createdat,status,acknowledgedat,resultid',alerts)
    for table,key in [('labtest','labtestid'),('testresult','resultid'),('labalert','alertid')]:
        out.write(f"SELECT setval(pg_get_serial_sequence('{table}','{key}'),(SELECT max({key}) FROM {table}));\n")
    out.write('COMMIT;\n')
print('Generated 20,000 lab tests, 16,000 results, 1,600 alerts; no real medical data.')
